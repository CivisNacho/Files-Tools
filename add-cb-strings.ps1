function Add-ReswEntries($file, $entries) {
    $content = Get-Content $file -Raw -Encoding UTF8
    $xml = New-Object System.Text.StringBuilder
    foreach ($key in $entries.Keys | Sort-Object) {
        $val = $entries[$key] -replace "&","&amp;" -replace "<","&lt;" -replace ">","&gt;"
        $null = $xml.AppendLine("  <data name=""$key"" xml:space=""preserve""><value>$val</value></data>")
    }
    $newBlock = $xml.ToString()
    $content = $content -replace "</root>", "$newBlock</root>"
    Set-Content $file -Value $content -Encoding UTF8 -NoNewline
}

